// Fuzz suite for MCP stdio framing (untrusted bytes from a hostile or broken MCP server).
//
// Driver seam: the framing logic was welded to StdioTransport's stdout read loop, so it
// was extracted verbatim into the exported StdioLineFramer (byte-feed seam + observable
// bufferedChars for the buffer-bound invariant). No behavior change; existing mcp tests
// stay green. Pipe read coalescing makes subprocess chunk boundaries nondeterministic,
// so the split-pattern differential and the buffer-bound assertions run through the
// seam; the behaviors that need a real process (EOF, zero-byte stream, the over-cap
// guard over a real pipe, handler-throw survival) use four tiny `bun -e` children.
//
// Reality pinned from the source (the MCP stdio transport here is NDJSON, NOT
// Content-Length framed): send() writes `json + "\n"`; the reader splits on "\n" only.
// "Content-Length: ..." headers are opaque line text, dispatched to the handler as
// ordinary (non-JSON, ignored) lines; they never steer framing, never trigger a wait
// for a declared body. "\r" is stripped by the trim() in StdioTransport dispatch, not
// by framing, so bare-CR terminators do NOT terminate lines. Over-cap partial lines are
// dropped and drained to the next "\n" (never dispatched, framing resumes after). EOF
// with an unterminated tail delivers nothing and fires close handlers. A throwing
// message handler is caught per-handler and logged; the transport keeps running.
//
// Invariants audited on every generated byte sequence:
//   1. garbage (header-shaped or not) never crashes, never merges with or splits a
//      neighboring line, and never leaves the framer waiting past a line boundary
//   2. for streams well under the cap, dispatch for EVERY chunk split pattern
//      (random, adversarial, byte-at-a-time, zero-byte chunks) equals one-feed dispatch
//   3. valid frames arrive in order and byte-intact amid malformed noise
//   4. bufferedChars never exceeds MAX_TRANSPORT_BUFFER_CHARS after any feed, and a
//      dispatched line is never a cut-off fragment (sentinel head+tail check)
//   5. EOF mid-frame / zero-byte stream: no crash, no hang (poll deadlines + test timeouts)

import { describe, it, expect } from "bun:test";
import {
  StdioLineFramer,
  StdioTransport,
  MAX_TRANSPORT_BUFFER_CHARS,
} from "@extensions/mcp-client/transports.ts";
import { makeRng, randomChunksBytes, type Rng } from "../fuzz/prng.ts";

const CAP = MAX_TRANSPORT_BUFFER_CHARS;

// ── Seam helpers ─────────────────────────────────────────────────────

/** Framer collecting raw lines (pre-trim, exactly what #dispatchMessage receives). */
function collectingFramer(): { raw: string[]; framer: StdioLineFramer; maxBuffer: () => number } {
  const raw: string[] = [];
  let maxBuffer = 0;
  const framer = new StdioLineFramer((line) => {
    raw.push(line);
  }, CAP);
  const feedOriginal = framer.feed.bind(framer);
  framer.feed = (chunk: Uint8Array) => {
    feedOriginal(chunk);
    if (framer.bufferedChars > maxBuffer) maxBuffer = framer.bufferedChars;
  };
  return { raw, framer, maxBuffer: () => maxBuffer };
}

/** Replicates StdioTransport.#dispatchMessage: trim, skip empty. */
function delivered(raw: string[]): string[] {
  return raw.map((l) => l.trim()).filter((l) => l.length > 0);
}

function feedAll(framer: StdioLineFramer, chunks: Uint8Array[]): void {
  for (const c of chunks) framer.feed(c);
}

function utf8(s: string): Uint8Array {
  return new TextEncoder().encode(s);
}

// Multibyte + emoji payloads: byte splits can bisect UTF-8 sequences, and the
// stateful TextDecoder must reassemble them (per-chunk toString would U+FFFD).
const validFrame = (id: number): string =>
  JSON.stringify({ jsonrpc: "2.0", id, result: { ok: id, text: `ünïcödé 🌍 ${id}` } });

const isFrame = (line: string): boolean => {
  try {
    const m = JSON.parse(line) as Record<string, unknown>;
    return m.jsonrpc === "2.0" && typeof m.id === "number";
  } catch {
    return false;
  };
}

// Header-shaped and general garbage. No entry contains "\n" (each is one line).
const GARBAGE: readonly string[] = [
  "Content-Length: abc",
  "Content-Length: -5",
  "Content-Length: 0",
  `Content-Length: ${CAP}`,
  `Content-Length: ${CAP * 10}`,
  "Content-Length: 999999999999999999999999999",
  "Content-Length 12",
  "content-length:12",
  "Content-Length:",
  "Content-Length:   ",
  "Content-Length: 4\rContent-Length: 8",
  "Content-Type: application/json",
  "\x00\x01\x02binary junk\x03",
  "}{ not json ][",
  '{"jsonrpc":"2.0"',
  "   ",
  "\r",
  "Content-Length: \t \x0b \x0c",
];

// ── 1. Garbage Content-Length is opaque line text ───────────────────

describe("mcp stdio framing: garbage Content-Length", () => {
  it("never crashes and is dispatched as ordinary lines", () => {
    for (const g of GARBAGE) {
      const { raw, framer } = collectingFramer();
      expect(() => framer.feed(utf8(g + "\n"))).not.toThrow();
      // Exactly-once: no "\n" inside any entry, so a terminated line must
      // dispatch whole (no drop, no duplicate, no fragment of a neighbor),
      // and never trigger a body wait (buffer fully flushed).
      expect(raw).toEqual([g]);
      expect(framer.bufferedChars).toBe(0);
    }
  });

  it("an LSP-style Content-Length frame dispatches header and body as separate lines", () => {
    // The transport does NOT honor Content-Length: the header line and the body
    // line are independent dispatches (both are handed to the handler, which
    // JSON.parse-drops the header and parses the body).
    const { raw, framer } = collectingFramer();
    framer.feed(utf8('Content-Length: 9\r\n\r\n{"jsonrpc":"2.0","id":1,"result":{}}\n'));
    expect(delivered(raw)).toEqual([
      "Content-Length: 9",
      '{"jsonrpc":"2.0","id":1,"result":{}}',
    ]);
  });

  it("multiple Content-Length headers never merge and never consume the body", () => {
    const { raw, framer } = collectingFramer();
    framer.feed(utf8("Content-Length: 1\r\nContent-Length: 2\r\n\r\n{}\n"));
    expect(delivered(raw)).toEqual(["Content-Length: 1", "Content-Length: 2", "{}"]);
  });

  it("an absurdly huge declared length does not make the framer wait for a body", () => {
    const { raw, framer } = collectingFramer();
    framer.feed(utf8(`Content-Length: ${CAP * 10}\n`));
    framer.feed(utf8('{"jsonrpc":"2.0","id":2,"result":{}}\n'));
    expect(delivered(raw)).toEqual([
      "Content-Length: " + CAP * 10,
      '{"jsonrpc":"2.0","id":2,"result":{}}',
    ]);
    expect(framer.bufferedChars).toBe(0);
  });

  it("missing-colon and CR-only terminators: only \\n frames", () => {
    // CR-only (classic-Mac line endings) is not a terminator: the stream sits in
    // the partial-line buffer, undelivered, until a \n or the cap arrives.
    const { raw, framer } = collectingFramer();
    framer.feed(utf8("a\rb\rc"));
    expect(raw).toEqual([]);
    expect(framer.bufferedChars).toBe(5);
    framer.feed(utf8("\n"));
    expect(delivered(raw)).toEqual(["a\rb\rc"]); // raw line keeps the CRs

    // CRLF terminates via the \n; the trailing \r is transport-trimmed.
    const c = collectingFramer();
    c.framer.feed(utf8("x\r\ny\r\n"));
    expect(c.raw).toEqual(["x\r", "y\r"]);
    expect(delivered(c.raw)).toEqual(["x", "y"]);
  });
});

// ── 2. Split-pattern differential vs one-feed ───────────────────────

describe("mcp stdio framing: split-pattern differential", () => {
  // Mix of valid frames and garbage lines; total far below the cap so the
  // over-cap drain (which is chunk-boundary sensitive by design, tested
  // separately) cannot influence the comparison.
  function mixedStream(count: number): Uint8Array {
    const lines: string[] = [];
    for (let i = 0; i < count; i++) {
      lines.push(validFrame(i));
      lines.push(GARBAGE[i % GARBAGE.length]!);
    }
    return utf8(lines.join("\n") + "\n");
  }

  it("every split pattern delivers exactly what one feed delivers", () => {
    const bytes = mixedStream(8);
    expect(bytes.length).toBeLessThan(1024);

    const baseline = collectingFramer();
    baseline.framer.feed(bytes);

    const rng = makeRng(0x6d63_801);
    const mismatches: { iter: number; mode: string }[] = [];
    for (let i = 0; i < 250 && mismatches.length < 3; i++) {
      const mode = rng.bool() ? "random" : "adversarial";
      let chunks = randomChunksBytes(rng, bytes, 2 + rng.int(20), mode);
      if (rng.bool()) {
        // interleave zero-byte chunks: feeds must be no-ops
        const withEmpty: Uint8Array[] = [];
        for (const c of chunks) {
          if (rng.bool()) withEmpty.push(new Uint8Array(0));
          withEmpty.push(c);
        }
        chunks = withEmpty;
      }
      const run = collectingFramer();
      feedAll(run.framer, chunks);
      if (JSON.stringify(run.raw) !== JSON.stringify(baseline.raw)) {
        mismatches.push({ iter: i, mode });
      }
      expect(run.framer.bufferedChars).toBe(baseline.framer.bufferedChars);
      expect(run.maxBuffer()).toBeLessThanOrEqual(CAP);
    }
    expect(mismatches).toEqual([]);
  });

  it("byte-at-a-time on a small payload equals one-feed delivery", () => {
    const bytes = mixedStream(4);
    const baseline = collectingFramer();
    baseline.framer.feed(bytes);

    const run = collectingFramer();
    for (const b of bytes) run.framer.feed(new Uint8Array([b]));
    expect(run.raw).toEqual(baseline.raw);
    // byte-at-a-time must not split a multibyte char either: emoji survived intact
    expect(delivered(run.raw).some((l) => l.includes("🌍"))).toBe(true);
    expect(run.framer.bufferedChars).toBe(0);
  });

  it("a frame torn across the boundary mid-multibyte-sequence reassembles", () => {
    const line = validFrame(1) + "\n";
    const bytes = utf8(line);
    // cut in the middle of the emoji's 4-byte UTF-8 sequence
    const emojiAt = line.indexOf("🌍");
    expect(emojiAt).toBeGreaterThan(0);
    const cut = utf8(line.slice(0, emojiAt)).length + 2;
    const run = collectingFramer();
    run.framer.feed(bytes.subarray(0, cut));
    run.framer.feed(bytes.subarray(cut));
    expect(delivered(run.raw)).toEqual([line.trimEnd()]);
    expect(run.raw[0]!.includes("\uFFFD")).toBe(false);
  });
});

// ── 3. Notification bursts interleaved with malformed lines ─────────

describe("mcp stdio framing: bursts amid malformed noise", () => {
  const VALID_COUNT = 40;

  // 40 valid frames, garbage sprinkled between them, some noise lines also
  // JSON-parseable-but-not-frames to keep the ordering audit honest.
  function burstStream(rng: Rng): Uint8Array {
    const lines: string[] = [];
    for (let i = 0; i < VALID_COUNT; i++) {
      lines.push(validFrame(i));
      lines.push(GARBAGE[rng.int(GARBAGE.length)]!);
      if (rng.bool()) lines.push('{"jsonrpc":"2.0","method":"notifications/progress"}');
    }
    return utf8(lines.join("\n") + "\n");
  }

  it("valid frames arrive in order, byte-intact, for any split pattern", () => {
    const rng = makeRng(0x6d63_802);
    const failures: { iter: number }[] = [];
    for (let i = 0; i < 60 && failures.length < 3; i++) {
      const bytes = burstStream(rng);
      const chunks = randomChunksBytes(rng, bytes, 2 + rng.int(30), rng.bool() ? "random" : "adversarial");
      const run = collectingFramer();
      feedAll(run.framer, chunks);
      const ids = delivered(run.raw).filter(isFrame).map((l) => (JSON.parse(l) as { id: number }).id);
      let bad = ids.length !== VALID_COUNT;
      for (let k = 0; !bad && k < VALID_COUNT; k++) {
        if (ids[k] !== k) bad = true;
        // byte-intact: the re-rendered frame must appear verbatim in the stream
        else if (!run.raw.some((r) => r.trim() === validFrame(k))) bad = true;
      }
      if (bad) failures.push({ iter: i });
    }
    expect(failures).toEqual([]);
  });

  it("a malformed line never corrupts its neighbors' framing", () => {
    // With a fixed stream, every split delivers the identical ordered line set:
    // noise cannot swallow a neighboring frame or glue two frames together.
    const rng = makeRng(0x6d63_803);
    const bytes = utf8(
      GARBAGE.map((g) => `${g}\n`).join("") +
      [validFrame(0), validFrame(1), validFrame(2)].join("\n") + "\n",
    );
    const baseline = collectingFramer();
    baseline.framer.feed(bytes);
    const expected = delivered(baseline.raw).filter(isFrame);
    expect(expected).toEqual([validFrame(0), validFrame(1), validFrame(2)]);

    for (let i = 0; i < 80; i++) {
      const chunks = randomChunksBytes(rng, bytes, 2 + rng.int(25), i % 2 ? "adversarial" : "random");
      const run = collectingFramer();
      feedAll(run.framer, chunks);
      expect(delivered(run.raw).filter(isFrame)).toEqual(expected);
    }
  });
});

// ── 4. Buffer cap ───────────────────────────────────────────────────

describe("mcp stdio framing: buffer cap", () => {
  it("buffer holds exactly cap chars, trips only past cap, and drains to the next boundary", () => {
    const { raw, framer } = collectingFramer();
    framer.feed(utf8("x".repeat(CAP)));
    expect(framer.bufferedChars).toBe(CAP); // strict >: at cap is still buffered
    expect(raw).toEqual([]);

    framer.feed(utf8("y")); // cap crossed: partial dropped, draining
    expect(framer.bufferedChars).toBe(0);
    framer.feed(utf8("tail-without-newline")); // still draining
    expect(framer.bufferedChars).toBe(0);
    expect(raw).toEqual([]);
    framer.feed(utf8("\n")); // drain ends at the oversized line's terminator
    expect(raw).toEqual([]); // nothing of the oversized line ever dispatched
    framer.feed(utf8("resumed\n"));
    expect(delivered(raw)).toEqual(["resumed"]);
  });

  it("a chunk crossing the cap WITH the line terminator dispatches the line whole", () => {
    // The dispatch loop runs BEFORE the cap check: the cap guards only the
    // unflushed tail, so a line completed by the very chunk that would push it
    // over cap dispatches intact. Split-sensitivity (line dropped) requires the
    // boundary to fall mid-line with no terminator in that chunk; pinned next.
    const { raw, framer } = collectingFramer();
    framer.feed(utf8("a".repeat(CAP)));
    framer.feed(utf8("b\nnext\n")); // tail completed within this feed: dispatched
    expect(delivered(raw)).toEqual(["a".repeat(CAP) + "b", "next"]);
    expect(framer.bufferedChars).toBe(0);
  });

  it("a huge chunk of complete short lines dispatches everything (cap bounds the tail only)", () => {
    const lines: string[] = [];
    for (let i = 0; i < 2100; i++) lines.push(`${i}|${"x".repeat(990)}|${i}`);
    const chunk = utf8(lines.join("\n") + "\n");
    expect(chunk.length).toBeGreaterThan(CAP);
    const { raw, framer } = collectingFramer();
    framer.feed(chunk);
    expect(raw.length).toBe(lines.length); // none dropped: each tail stayed under cap
    expect(framer.bufferedChars).toBe(0);
  });

  it("fuzz: bounded buffer under garbage floods; complete lines never dispatch truncated", () => {
    const rng = makeRng(0x6d63_804);
    const violations: string[] = [];
    // Sentinel lines embed their number at head and tail: a dispatched sentinel
    // is provably whole iff it starts AND ends with the same number.
    let nextSentinel = 0;
    const classify = (l: string): "frame" | "sentinel" | "junk" | "bad" => {
      if (isFrame(l)) return "frame";
      const m = l.match(/^L(\d+)\|x*\|(\d+)$/);
      if (m && m[1] === m[2]) return "sentinel";
      if (/^x+$/.test(l)) return "junk";
      return "bad";
    };

    for (let round = 0; round < 30 && violations.length < 3; round++) {
      const { raw, framer } = collectingFramer();

      // Phase A: complete lines (junk, sentinels, frames) fed in random
      // chunks, total far below cap: every line must arrive whole.
      const lines: string[] = [];
      const sentinels: string[] = [];
      for (let i = 0; i < 12; i++) {
        const roll = rng.int(3);
        if (roll === 0) {
          const n = nextSentinel++;
          const s = `L${n}|${"x".repeat(rng.int(300))}|${n}`;
          sentinels.push(s);
          lines.push(s);
        } else if (roll === 1) {
          lines.push(validFrame(rng.int(1000)));
        } else {
          lines.push("x".repeat(1 + rng.int(500)));
        }
      }
      const bytes = utf8(lines.join("\n") + "\n");
      for (const piece of randomChunksBytes(rng, bytes, 2 + rng.int(30), rng.bool() ? "random" : "adversarial")) {
        framer.feed(piece);
        if (framer.bufferedChars > CAP) violations.push(`buffer ${framer.bufferedChars} > cap ${CAP}`);
      }
      const dispatched = delivered(raw);
      for (const l of dispatched) {
        if (classify(l) === "bad") violations.push(`bad dispatch: ${JSON.stringify(l.slice(0, 60))}`);
      }
      // below-cap sentinels must all be delivered, whole, in order
      const gotSentinels = dispatched.filter((l) => classify(l) === "sentinel");
      if (gotSentinels.join("\u0000") !== sentinels.join("\u0000")) {
        violations.push(`sentinel loss/tampering: expected ${sentinels.length}, got ${gotSentinels.length}`);
      }

      // Phase B: cap burst without terminators (pipe-like 64K pieces): the
      // buffer stays bounded, nothing dispatches, and framing resumes after a
      // lone-terminator chunk.
      raw.length = 0;
      let fed = 0;
      while (fed < CAP + 65536 && violations.length < 3) {
        const piece = "x".repeat(65536); // no newline in the burst
        framer.feed(utf8(piece));
        fed += piece.length;
        if (framer.bufferedChars > CAP) violations.push(`flood buffer ${framer.bufferedChars} > cap ${CAP}`);
        if (raw.length > 0) violations.push("dispatch during unterminated flood");
      }
      framer.feed(utf8("\n")); // drain boundary: the oversized line dies here
      if (raw.length > 0) violations.push(`oversized line leaked ${raw.length} dispatch(es)`);
      framer.feed(utf8("after\n"));
      if (delivered(raw).join() !== "after") violations.push(`framing not resumed: ${JSON.stringify(raw)}`);
    }
    expect(violations).toEqual([]);
  });

  it("cap trip is split-sensitive when the boundary falls mid-line (documented drain semantics)", () => {
    // One feed dispatches even a past-cap line (complete lines dispatch as
    // flushed; the cap guards the unflushed TAIL only). The same bytes split so
    // that a feed ENDS past cap with no terminator trip the drain and the line
    // dies. Both behaviors are intentional in-source design.
    const payload = utf8("z".repeat(CAP + 10) + "\n");
    const single = collectingFramer();
    single.framer.feed(payload);
    expect(delivered(single.raw)).toEqual(["z".repeat(CAP + 10)]);

    const split = collectingFramer();
    split.framer.feed(payload.subarray(0, CAP + 5)); // ends mid-line, past cap
    expect(split.framer.bufferedChars).toBe(0); // tripped and cleared
    split.framer.feed(payload.subarray(CAP + 5)); // "zzzzz\n": drained away
    expect(delivered(split.raw)).toEqual([]);
    expect(split.framer.bufferedChars).toBe(0);
    // and both resume framing identically after the boundary
    split.framer.feed(utf8("ok\n"));
    single.framer.feed(utf8("ok\n"));
    expect(delivered(split.raw).at(-1)).toBe("ok");
    expect(delivered(single.raw).at(-1)).toBe("ok");
  });
});

// ── 5-7. Real-process behaviors (EOF, zero-byte, guard, handler throw) ──────

describe("mcp stdio framing: real transport", () => {
  async function until(cond: () => boolean, timeoutMs = 4000): Promise<boolean> {
    const start = Date.now();
    while (!cond() && Date.now() - start < timeoutMs) {
      await new Promise((r) => setTimeout(r, 15));
    }
    return cond();
  }

  it("EOF with an unterminated frame: nothing dispatched, close fires, no hang", async () => {
    const transport = new StdioTransport("bun", [
      "-e",
      'process.stdout.write(JSON.stringify({jsonrpc:"2.0",id:1,result:{ok:1}}));',
    ]);
    const received: string[] = [];
    let closed = false;
    const rmMsg = transport.onMessage((l) => received.push(l));
    const rmClose = transport.onClose(() => { closed = true; });
    try {
      expect(await until(() => closed)).toBe(true);
      expect(received).toEqual([]); // tail without \n is never dispatched
      expect(transport.exited).toBe(true);
    } finally {
      rmMsg();
      rmClose();
      await transport.destroy();
    }
  }, 8000);

  it("zero-byte stream: no dispatch, close fires, no crash", async () => {
    const transport = new StdioTransport("bun", ["-e", "void 0;"]);
    const received: string[] = [];
    let closed = false;
    const rmMsg = transport.onMessage((l) => received.push(l));
    const rmClose = transport.onClose(() => { closed = true; });
    try {
      expect(await until(() => closed)).toBe(true);
      expect(received).toEqual([]);
    } finally {
      rmMsg();
      rmClose();
      await transport.destroy();
    }
  }, 8000);

  it("terminator-less garbage past the cap trips the drain guard and framing resumes", async () => {
    // 2.5MB line with no internal newline (1.25x cap) over a real pipe: the
    // guard must drop and drain it, then deliver subsequent messages normally.
    // NOTE: the child uses console.log only; a huge async process.stdout.write
    // followed by a tiny write("\n") can reorder/lose bytes in Bun itself
    // (observed during authoring: a stray LF landed mid-flood), which would
    // test the child's stdio, not the framer.
    const transport = new StdioTransport("bun", [
      "-e",
      'console.log("before"); console.log("x".repeat(2500000)); console.log(JSON.stringify({jsonrpc:"2.0",id:7,result:{resumed:true}}));',
    ]);
    const received: string[] = [];
    const rmMsg = transport.onMessage((l) => received.push(l));
    try {
      expect(await until(() => received.some((l) => l.includes("resumed")))).toBe(true);
      expect(delivered(received)).toEqual([
        "before",
        '{"jsonrpc":"2.0","id":7,"result":{"resumed":true}}',
      ]);
      expect(received.every((l) => l.length < 1000)).toBe(true); // nothing oversized dispatched
    } finally {
      rmMsg();
      await transport.destroy();
    }
  }, 10000);

  it("a throwing message handler is swallowed: transport survives and keeps delivering", async () => {
    const uncaught: unknown[] = [];
    const onUncaught = (e: unknown) => { uncaught.push(e); };
    process.on("uncaughtException", onUncaught);
    const transport = new StdioTransport("bun", [
      "-e",
      'console.log("poison"); setTimeout(() => console.log(JSON.stringify({jsonrpc:"2.0",id:3,result:{ok:true}})), 60); setInterval(() => {}, 10000);',
    ]);
    const received: string[] = [];
    let closed = false;
    const rmMsg = transport.onMessage((l) => {
      received.push(l);
      if (l === "poison") throw new Error("handler exploded");
    });
    const rmClose = transport.onClose(() => { closed = true; });
    try {
      expect(await until(() => received.length >= 2)).toBe(true);
      expect(received[0]).toBe("poison"); // the throw happened, and was caught
      expect(delivered(received)[1]).toBe('{"jsonrpc":"2.0","id":3,"result":{"ok":true}}');
      expect(uncaught).toEqual([]); // pin: caught in #dispatchMessage and logged
      expect(closed).toBe(false); // transport NOT torn down by a handler throw
    } finally {
      process.off("uncaughtException", onUncaught);
      rmMsg();
      rmClose();
      await transport.destroy();
    }
  }, 8000);
});
